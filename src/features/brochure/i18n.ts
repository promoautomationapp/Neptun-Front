let language =
  localStorage.getItem("neptun-studio-language") === "en" ? "en" : "sq";
if (typeof document !== "undefined") document.documentElement.lang = language;
export function getLanguage() {
  return language;
}
export function setLanguage(value: string) {
  language = value === "sq" ? "sq" : "en";
  localStorage.setItem("neptun-studio-language", language);
  document.documentElement.lang = language;
}
export function t(text: unknown) {
  const value = String(text ?? "");
  return language === "sq" ? translations[value] || value : value;
}
